function t(key, vars) {
    let s = STR[lang][key]
    if (s === undefined) s = STR.en[key]
    if (s === undefined) return key
    if (vars) {
        for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k])
    }
    return s
}

function detect_lang() {
    try {
        const saved = localStorage.getItem(LANG_KEY)
        if (saved === 'en' || saved === 'pt') return saved
    } catch { /* storage may be blocked */ }
    return (navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

// Translates the static markup: data-i18n (text), data-i18n-html, data-i18n-title, data-i18n-placeholder, data-i18n-aria
function apply_i18n(root) {
    root = root || document
    if (root === document) {
        document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en'
        document.title = t('app.title')
        const desc = document.querySelector('meta[name="description"]')
        if (desc) desc.setAttribute('content', t('app.description'))
        const btn = document.getElementById('langBtn')
        if (btn) {
            const here = lang === 'pt' ? 'Português (Brasil)' : 'English'
            const there = lang === 'pt' ? 'English' : 'Português (Brasil)'
            document.getElementById('langCode').textContent = lang === 'pt' ? 'PT' : 'EN'
            btn.setAttribute('aria-label', t('top.lang_aria', { name: here }))
            btn.title = t('top.lang_to', { name: there })
        }
    }
    for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n)
    for (const e of root.querySelectorAll('[data-i18n-html]')) e.innerHTML = t(e.dataset.i18nHtml)
    for (const e of root.querySelectorAll('[data-i18n-title]')) e.title = t(e.dataset.i18nTitle)
    for (const e of root.querySelectorAll('[data-i18n-placeholder]')) e.placeholder = t(e.dataset.i18nPlaceholder)
    for (const e of root.querySelectorAll('[data-i18n-aria]')) e.setAttribute('aria-label', t(e.dataset.i18nAria))
}

function set_lang(next) {
    lang = next === 'pt' ? 'pt' : 'en'
    try {
        localStorage.setItem(LANG_KEY, lang)
    } catch { /* storage may be blocked */ }
    apply_i18n()
    if (typeof on_lang_change === 'function') on_lang_change()
}

