function subsystem_name(name) {
    const s = SUBSYSTEMS[name]
    return s ? s[lang === 'pt' ? 1 : 0] : name
}

function error_code_text(sub_name, code, mode_label) {
    if (sub_name === 'FLIGHT_MODE') return t('err.flightmode', { n: mode_label })
    if (sub_name === 'EKF_PRIMARY') return t('err.ekf_primary', { n: code })
    const specific = ERROR_CODES[sub_name] && ERROR_CODES[sub_name][code]
    if (specific) return t(specific)
    const failsafe = sub_name && sub_name.startsWith('FAILSAFE_')
    if (code === 0) return t('err.resolved')
    if (code === 1) return t(failsafe ? 'err.failsafe' : 'err.failed_init')
    if (code === 4) return t('err.unhealthy')
    return t('err.unknown')
}

